import {test,expect,type Page} from '@playwright/test';
async function enter(page:Page){
 await page.goto('/telegram-dashboard/?qa=1');
 await page.getByRole('textbox',{name:'Как тебя зовут?'}).fill('Task V2 QA');
 await page.getByRole('button',{name:'Войти в QA Sandbox'}).click();
 await expect(page.getByText('Добро пожаловать')).toBeVisible();
 await page.goto('/telegram-dashboard/?qa=1#/tab/buffer');
}
test('quick capture chooses existing category and preserves text on cancel',async({page})=>{
 await enter(page);
 const input=page.getByRole('textbox',{name:'Быстро добавить задачу'});
 await input.fill('Записаться к мастеру');
 await input.press('Enter');
 const dialog=page.getByRole('dialog',{name:'Категория новой задачи'});
 await expect(dialog).toBeVisible();
 await expect(dialog).toContainText('Записаться к мастеру');
 await page.keyboard.press('Escape');
 await expect(dialog).toHaveCount(0);
 await expect(input).toHaveValue('Записаться к мастеру');
 await input.press('Enter');
 const choices=dialog.getByRole('group',{name:'Выбрать категорию для задачи'}).getByRole('button');
 await expect(choices.first()).toBeVisible();
 const categoryName=(await choices.first().innerText()).trim();
 await choices.first().click();
 await expect(dialog).toHaveCount(0);
 await expect(input).toHaveValue('');
 await expect(page.locator('.task-copy').filter({hasText:'Записаться к мастеру'})).toHaveCount(1);
 await expect(page.locator('.buffer-group').filter({hasText:categoryName}).locator('.task-copy').filter({hasText:'Записаться к мастеру'})).toBeVisible();
});
test('quick capture creates category and deadline time persists with native priority',async({page})=>{
 await page.setViewportSize({width:390,height:830});
 await enter(page);
 const input=page.getByRole('textbox',{name:'Быстро добавить задачу'});
 await input.fill('Записаться на стрижку');
 await input.press('Enter');
 const dialog=page.getByRole('dialog',{name:'Категория новой задачи'});
 await dialog.getByRole('button',{name:'Создать категорию'}).click();
 await dialog.getByRole('textbox',{name:'Название категории для задачи'}).fill('Календарь');
 await dialog.getByRole('button',{name:'Создать и добавить'}).click();
 await expect(dialog).toHaveCount(0);
 await expect(page.locator('.task-copy').filter({hasText:'Записаться на стрижку'})).toBeVisible();
 await page.locator('.task-copy').filter({hasText:'Записаться на стрижку'}).click();
 await page.getByRole('button',{name:'Свойства',exact:true}).click();
 const inspector=page.locator('#task-inspector');
 await expect(inspector).toBeVisible();
 await expect(inspector.getByRole('button',{name:'Настроить свойство Приоритет'})).toBeVisible();
 await expect(inspector.getByRole('button',{name:'Настроить свойство Дедлайн'})).toBeVisible();
 await expect(inspector.getByRole('button',{name:'Выбрать категорию'})).toContainText('Календарь');
 const bg=await inspector.evaluate(el=>getComputedStyle(el).backgroundColor);
 expect(bg).toBe('rgba(0, 0, 0, 0)');
 await inspector.getByRole('button',{name:/Выбрать срок/}).click();
 await inspector.getByRole('button',{name:'Завтра',exact:true}).click();
 const date=await inspector.getByLabel('Дата дедлайна').inputValue();
 expect(date).toMatch(/^\d{4}-\d{2}-\d{2}$/);
 await inspector.getByLabel('Время дедлайна').fill('17:30');
 await inspector.getByRole('button',{name:'Сохранить',exact:true}).click();
 await expect(inspector.getByRole('button',{name:/17:30/})).toContainText('17:30');
 await page.reload();
 await page.getByRole('button',{name:'Свойства',exact:true}).click();
 await expect(page.locator('#task-inspector').getByRole('button',{name:/17:30/})).toContainText('17:30');
 await page.getByRole('button',{name:'Свойства',exact:true}).click();
 await expect(page.locator('#task-inspector')).toBeHidden();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(2);
});
